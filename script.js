const menuButton = document.querySelector(".menu-button");
const mobileMenu = document.querySelector(".mobile-menu");
const languageButtons = document.querySelectorAll(".lang-button");

function setMenu(open) {
  menuButton.setAttribute("aria-expanded", String(open));
  menuButton.setAttribute("aria-label", open
    ? (document.documentElement.lang === "ru" ? "Закрыть меню" : "Close menu")
    : (document.documentElement.lang === "ru" ? "Открыть меню" : "Open menu"));
  mobileMenu.hidden = !open;
  document.body.classList.toggle("menu-open", open);
}

function setLanguage(lang) {
  const isEnglish = lang === "en";
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (isEnglish && translations.en[key]) {
      element.textContent = translations.en[key];
    } else if (!isEnglish && element.dataset.ru) {
      element.textContent = element.dataset.ru;
    }
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const key = element.dataset.i18nAria;
    if (isEnglish && translations.en[key]) {
      element.setAttribute("aria-label", translations.en[key]);
    } else if (!isEnglish && element.dataset.ruAria) {
      element.setAttribute("aria-label", element.dataset.ruAria);
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (isEnglish && translations.en[key]) {
      element.alt = translations.en[key];
    } else if (!isEnglish && element.dataset.ruAlt) {
      element.alt = element.dataset.ruAlt;
    }
  });

  document.querySelectorAll(".dynamic-link").forEach((link) => {
    link.href = isEnglish ? link.dataset.hrefEn : link.dataset.hrefRu;
  });

  languageButtons.forEach((button) => {
    const active = button.dataset.lang === lang;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  const meta = isEnglish ? enMeta : ruMeta;
  document.title = meta.title;
  document.querySelector('meta[name="description"]').setAttribute("content", meta.description);
  localStorage.setItem("svetlab-language", lang);
  setMenu(false);
}

document.querySelectorAll("[data-i18n], [data-i18n-aria], [data-i18n-alt]").forEach((element) => {
  if (element.dataset.i18n) element.dataset.ru = element.textContent;
  if (element.dataset.i18nAria) element.dataset.ruAria = element.getAttribute("aria-label") || "";
  if (element.dataset.i18nAlt) element.dataset.ruAlt = element.getAttribute("alt") || "";
});

menuButton.addEventListener("click", () => {
  setMenu(menuButton.getAttribute("aria-expanded") !== "true");
});

mobileMenu.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => setMenu(false));
});

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") setMenu(false);
});

const revealElements = document.querySelectorAll(".reveal");

if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12, rootMargin: "0px 0px -24px" });

  revealElements.forEach((element) => observer.observe(element));
} else {
  revealElements.forEach((element) => element.classList.add("is-visible"));
}
